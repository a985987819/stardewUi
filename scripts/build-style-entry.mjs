// Generates the `stardew-valley-ui/auto` entry point: a thin wrapper that
// re-exports the library root and injects the built stylesheet at runtime, so
// consumers can skip `import 'stardew-valley-ui/style.css'`.
//
// Why a post-build script instead of a second Vite entry:
// Vite's library mode always extracts CSS into a standalone `.css` asset and
// strips the import from the JS bundle (components pull their own CSS Modules,
// so no single source file owns the aggregated stylesheet). The only way to get
// the *aggregate* CSS into JS is to read the emitted file and embed it.
//
// Runs after `vite build --mode lib` + `tsc -p tsconfig.lib.json`.
// See docs/publishing.md and docs/consumer-integration.md.

import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const projectRoot = path.resolve(import.meta.dirname, '..')
const distDir = path.join(projectRoot, 'dist')

const CSS_FILE = 'stardew-valley-ui.css'
const ESM_FILE = 'stardew-valley-ui.auto.mjs'
const CJS_FILE = 'stardew-valley-ui.auto.cjs'
const TYPES_FILE = 'auto.d.ts'
const STYLE_ID = 'stardew-valley-ui-styles'

// Custom property used to detect "these styles are already on the page".
// It is appended to the shipped stylesheet so that importing both the explicit
// `style.css` subpath and the `/auto` entry never doubles the payload.
const SENTINEL = '--stardew-valley-ui-styles'
const SENTINEL_RULE = `:root{${SENTINEL}:1}`

const cssPath = path.join(distDir, CSS_FILE)

let css = await readFile(cssPath, 'utf8')

if (!css.includes(`${SENTINEL}:`)) {
  css = `${css.replace(/\s*$/, '')}\n${SENTINEL_RULE}\n`
  await writeFile(cssPath, css, 'utf8')
  console.log(`[style-entry] appended ${SENTINEL} sentinel to ${CSS_FILE}`)
}

// JSON.stringify is the safest way to embed CSS as a JS string literal: it
// escapes quotes, backslashes and line terminators.
const cssLiteral = JSON.stringify(css)

const banner = `// Generated by scripts/build-style-entry.mjs — do not edit.
// Re-exports the library root and injects the bundled stylesheet on import.`

const instrument = `const STYLE_ID = '${STYLE_ID}'
const SENTINEL = '${SENTINEL}'
const CSS = ${cssLiteral}

const needsInjection = () => {
  if (typeof document === 'undefined' || typeof getComputedStyle !== 'function') return false
  if (document.getElementById(STYLE_ID)) return false
  // The explicit 'stardew-valley-ui/style.css' entry ships the same sentinel,
  // so a project that imports both paths still ends up with one copy of the CSS.
  return getComputedStyle(document.documentElement).getPropertyValue(SENTINEL).trim() === ''
}

if (needsInjection()) {
  const style = document.createElement('style')
  style.id = STYLE_ID
  style.setAttribute('data-stardew-valley-ui', 'styles')
  style.textContent = CSS
  document.head.appendChild(style)
}
`

const esm = `${banner}

export * from './stardew-valley-ui.mjs'

${instrument}`

const cjs = `${banner}

'use strict'

module.exports = require('./stardew-valley-ui.cjs')

${instrument}`

const declaration = `// Generated by scripts/build-style-entry.mjs — do not edit.
export * from './index'
`

await writeFile(path.join(distDir, ESM_FILE), esm, 'utf8')
await writeFile(path.join(distDir, CJS_FILE), cjs, 'utf8')
await writeFile(path.join(distDir, TYPES_FILE), declaration, 'utf8')

console.log(`[style-entry] wrote ${ESM_FILE}, ${CJS_FILE}, ${TYPES_FILE} (${(css.length / 1024).toFixed(1)} KB of CSS embedded)`)
